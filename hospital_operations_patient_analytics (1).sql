DROP DATABASE IF EXISTS hospital_analytics;
CREATE DATABASE hospital_analytics;
USE hospital_analytics;

CREATE TABLE Departments 
(department_id INT PRIMARY KEY,
 department_name VARCHAR(100),
 description VARCHAR(255));
 
 select*from Departments;
 
CREATE TABLE Doctors
(doctor_id INT PRIMARY KEY,
 doctor_name VARCHAR(120),
 gender VARCHAR(20),
 department_id INT,
 designation VARCHAR(50),
 FOREIGN KEY (department_id) REFERENCES Departments(department_id));
 select*from doctors;
 
CREATE TABLE Patients
(patient_id INT PRIMARY KEY,
first_name VARCHAR(50),
last_name VARCHAR(50),
gender VARCHAR(20),
date_of_birth DATE,
city VARCHAR(50));
select*from patients;

CREATE TABLE Medications 
(medication_id INT PRIMARY KEY, 
medication_name VARCHAR(120), 
form VARCHAR(30), 
dosage VARCHAR(30));
select*from medications;

CREATE TABLE Appointments 
(appointment_id INT PRIMARY KEY, 
patient_id INT, 
doctor_id INT, 
appointment_date DATE, 
appointment_time TIME, 
status VARCHAR(30), 
reason VARCHAR(100), 
FOREIGN KEY (patient_id) REFERENCES Patients(patient_id), 
FOREIGN KEY (doctor_id) REFERENCES Doctors(doctor_id));
select*from appointments;

CREATE TABLE Treatments 
(treatment_id INT PRIMARY KEY, 
appointment_id INT, 
patient_id INT, 
treatment_type VARCHAR(100), 
treatment_date DATE, 
treatment_cost DECIMAL(12,2), 
medication_id INT NULL, 
admission_type VARCHAR(30), 
FOREIGN KEY (appointment_id) REFERENCES Appointments(appointment_id), 
FOREIGN KEY (patient_id) REFERENCES Patients(patient_id), 
FOREIGN KEY (medication_id) REFERENCES Medications(medication_id));
select*from treatments;


CREATE TABLE Billing 
(bill_id INT PRIMARY KEY, 
treatment_id INT, 
patient_id INT, 
bill_date DATE, 
total_amount DECIMAL(12,2), 
insurance_covered DECIMAL(12,2), 
patient_paid DECIMAL(12,2), 
payment_status VARCHAR(30), 
FOREIGN KEY (treatment_id) REFERENCES Treatments(treatment_id), 
FOREIGN KEY (patient_id) REFERENCES Patients(patient_id));
select*from billing;


